import 'dart:io';

import 'package:ffigen/ffigen.dart';
import 'package:logging/logging.dart';

import '../common/library_exports.dart';
import 'delegate_facades.dart';
import 'exposure_rules.dart';
import 'inventory.dart';

/// The oldest iOS release the package supports.
final minIos = Version(18, 0, 0);

String get minIosLabel => '${minIos.major}.${minIos.minor}';

const _header = 'src/ios/bt_kit.h';
const _objectiveC = 'src/ios/bindings.g.m';
const _bindings = 'lib/src/native/ios/bindings.g.dart';
const _entryPoint = 'lib/ios.dart';
const _internalBarrel = 'lib/src/native/ios/bindings.dart';
const _inventory = 'doc/inventory/ios.md';

Future<void> generateIos() async {
  final sdk = await _iosSdk();
  await _generate(sdk, IosExposureRules());
  final rules = IosExposureRules(
    systemCreated: findSystemCreated(File(_bindings).readAsStringSync()),
  );
  await _generate(sdk, rules);

  final bindings = File(_bindings);
  final facades = addDelegateFacades(bindings.readAsStringSync());
  bindings.writeAsStringSync(facades.source);
  await Process.run('dart', ['format', _bindings]);

  await _writeLibraries(facades.protocols);
  writeIosInventory(
    File(_inventory),
    rules: rules,
    bindings: facades.source,
    sdkVersion: await _iosSdkVersion(),
    minIos: minIosLabel,
  );
}

Future<void> _generate(Directory sdk, IosExposureRules rules) => FfiGenerator(
  input: Input(
    entryPoints: [Uri.file(_header)],
    compilerOptions: [
      '-isysroot',
      sdk.path,
      '-target',
      'arm64-apple-ios$minIos',
      '-fobjc-arc',
    ],
    appendCompilerOptions: true,
  ),
  objectiveC: ObjectiveC(
    externalVersions: ExternalVersions(ios: Versions(min: minIos)),
  ),
  output: Output(
    dart: DartOutput(path: Uri.file(_bindings)),
    objectiveCFile: Uri.file(_objectiveC),
    preamble: '// Generated by tool/generate.dart. Do not edit.',
  ),
  visitors: rules.visitors,
).generate(logger: _logger);

Future<Directory> _iosSdk() async =>
    Directory((await _xcrun(['--sdk', 'iphoneos', '--show-sdk-path'])).trim());

Future<String> _iosSdkVersion() async =>
    (await _xcrun(['--sdk', 'iphoneos', '--show-sdk-version'])).trim();

Future<String> _xcrun(List<String> args) async {
  final result = await Process.run('xcrun', args);
  if (result.exitCode != 0) {
    throw ProcessException('xcrun', args, '${result.stderr}');
  }
  return '${result.stdout}';
}

final _logger = Logger('ffigen')
  ..onRecord.listen((record) {
    if (record.level >= Level.SEVERE) stderr.writeln(record.message);
  });

/// Writes `lib/ios.dart`, which exports the bindings without the protocol
/// builders and the methods for invoking delegates, which only exist for
/// interop, and the internal barrel Layer 2 imports.
Future<void> _writeLibraries(List<String> protocols) async {
  final collisions = await nameCollisions(
    File(_bindings),
    declaredNames(File(_bindings)),
    libraries: const ['dart:core', 'package:objective_c/objective_c.dart'],
  );
  await writeExports(
    File(_entryPoint),
    header:
        '''

/// Layer 1 for iOS: direct bindings to CoreBluetooth, AccessorySetupKit and
/// ExternalAccessory.
///
/// APIs deprecated at or before iOS $minIosLabel are omitted. Newer APIs
/// check the running iOS version and throw `OsVersionError` when missing.
/// Delegates are implemented with their `implement` factory.
library;
''',
    exports: ["export 'package:objective_c/objective_c.dart';"],
    bindings: 'src/native/ios/bindings.g.dart',
    hidden: {
      ...collisions,
      for (final protocol in protocols) ...[
        '$protocol\$Builder',
        '$protocol\$Methods',
      ],
    },
  );
  await writeExports(
    File(_internalBarrel),
    header: '\n/// Layer 1 as Layer 2 sees it, plumbing included.\nlibrary;\n',
    exports: const [],
    bindings: 'bindings.g.dart',
    hidden: collisions,
  );
}
