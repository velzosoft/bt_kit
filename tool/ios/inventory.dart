import 'dart:io';

import 'exposure_rules.dart';

/// Writes the iOS API inventory: every declaration Layer 1 exposes, the iOS
/// version that introduced it, and every omission the rules made.
void writeIosInventory(
  File file, {
  required IosExposureRules rules,
  required String bindings,
  required String sdkVersion,
  required String minIos,
}) {
  final introduced = {
    for (final match in RegExp(
      r"checkOsVersionInternal\(\s*'(\w+)',\s*iOS: \(\w+, \((\d+), (\d+), (\d+)\)\)",
    ).allMatches(bindings))
      match.group(1)!: '${match.group(2)}.${match.group(3)}',
  };
  final s = StringBuffer()
    ..writeln('# iOS API inventory')
    ..writeln()
    ..writeln(
      'Generated by `tool/generate.dart` from the iOS $sdkVersion SDK '
      '(minimum iOS $minIos). Do not edit.',
    )
    ..writeln()
    ..writeln(
      'APIs deprecated at or before iOS $minIos are omitted by FFIgen. '
      'APIs introduced later than iOS $minIos check the running version and '
      'throw `OsVersionError` when unavailable.',
    )
    ..writeln();

  for (final MapEntry(key: framework, value: prefix)
      in IosExposureRules.frameworks.entries) {
    final names =
        rules.included.keys.where((n) => n.startsWith(prefix)).toList()..sort();
    s
      ..writeln('## $framework')
      ..writeln()
      ..writeln('| Declaration | Kind | Introduced |')
      ..writeln('|---|---|---|');
    for (final name in names) {
      s.writeln(
        '| `$name` | ${rules.included[name]} | ${introduced[name] ?? '–'} |',
      );
    }
    s.writeln();
  }

  s
    ..writeln('## Omitted')
    ..writeln()
    ..writeln('| Declaration | Member | Reason |')
    ..writeln('|---|---|---|');
  final omitted = {
    for (final o in rules.omitted) '${o.declaration}|${o.member}': o,
  }.values.toList()..sort((a, b) => a.declaration.compareTo(b.declaration));
  for (final o in omitted) {
    s.writeln('| `${o.declaration}` | `${o.member}` | ${o.omission.reason} |');
  }

  file
    ..createSync(recursive: true)
    ..writeAsStringSync(s.toString());
}
