// ignore_for_file: implementation_imports

import 'dart:io';

import 'package:jnigen/src/elements/elements.dart' as ast;
import 'package:path/path.dart' as p;

import 'callback_classes.dart';

const _header = '// Generated by tool/generate.dart. Do not edit.';

/// Writes one Java adapter per callback class into [directory], replacing
/// any adapters from a previous run.
void writeJavaAdapters(Directory directory, List<CallbackClass> classes) {
  if (directory.existsSync()) directory.deleteSync(recursive: true);
  directory.createSync(recursive: true);
  for (final callbackClass in classes) {
    File(p.join(directory.path, '${callbackClass.adapterName}.java'))
        .writeAsStringSync(_renderAdapter(callbackClass));
  }
}

String _renderAdapter(CallbackClass c) {
  final s = StringBuffer()
    ..writeln(_header)
    ..writeln('package ${CallbackClass.adapterPackage};')
    ..writeln()
    ..writeln('@SuppressWarnings("deprecation")')
    ..writeln(
      'public final class ${c.adapterName} extends ${_javaName(c.binaryName)} {',
    )
    ..writeln('  public interface Listener {');
  for (final method in c.callbacks) {
    s.writeln('    void ${method.name}(${_params(method)});');
  }
  s.writeln('  }');
  s.writeln();
  if (c.isService) {
    _writeServiceState(s, c);
  } else {
    _writeInstanceState(s, c);
  }
  for (final method in c.callbacks) {
    final args = method.params.map((param) => param.name).join(', ');
    s
      ..writeln()
      ..writeln('  @Override')
      ..writeln('  public void ${method.name}(${_params(method)}) {');
    if (c.isService) {
      s
        ..writeln('    Listener listener = btKitListener;')
        ..writeln('    if (listener != null) listener.${method.name}($args);');
    } else {
      s.writeln('    btKitListener.${method.name}($args);');
    }
    s.writeln('  }');
  }
  s.writeln('}');
  return s.toString();
}

void _writeInstanceState(StringBuffer s, CallbackClass c) {
  s
    ..writeln('  private final Listener btKitListener;')
    ..writeln()
    ..writeln('  public ${c.adapterName}(Listener listener) {')
    ..writeln('    btKitListener = listener;')
    ..writeln('  }');
}

void _writeServiceState(StringBuffer s, CallbackClass c) {
  s
    ..writeln('  private static volatile Listener btKitListener;')
    ..writeln('  private static volatile ${c.adapterName} running;')
    ..writeln()
    ..writeln('  public static void install(Listener listener) {')
    ..writeln('    btKitListener = listener;')
    ..writeln('  }')
    ..writeln()
    ..writeln('  public static ${c.adapterName} current() {')
    ..writeln('    return running;')
    ..writeln('  }')
    ..writeln()
    ..writeln('  @Override')
    ..writeln('  public void onCreate() {')
    ..writeln('    super.onCreate();')
    ..writeln('    running = this;')
    ..writeln('  }')
    ..writeln()
    ..writeln('  @Override')
    ..writeln('  public void onDestroy() {')
    ..writeln('    running = null;')
    ..writeln('    super.onDestroy();')
    ..writeln('  }');
}

String _params(ast.Method method) => method.params
    .map((param) => '${_javaType(param.type)} ${param.name}')
    .join(', ');

String _javaType(ast.ReferredType type) => switch (type) {
  ast.PrimitiveType(:final name) => name,
  ast.ArrayType(:final elementType) => '${_javaType(elementType)}[]',
  ast.TypeVar(:final name) => name,
  ast.Wildcard(:final extendsBound?) => '? extends ${_javaType(extendsBound)}',
  ast.Wildcard(:final superBound?) => '? super ${_javaType(superBound)}',
  ast.Wildcard() => '?',
  ast.DeclaredType(:final binaryName, :final params) =>
    params.isEmpty
        ? _javaName(binaryName)
        : '${_javaName(binaryName)}<${params.map(_javaType).join(', ')}>',
};

String _javaName(String binaryName) => binaryName.replaceAll(r'$', '.');
