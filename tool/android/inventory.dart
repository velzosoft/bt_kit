// ignore_for_file: implementation_imports

import 'dart:io';

import 'package:jnigen/src/elements/elements.dart' as ast;

import 'callback_classes.dart';
import 'exposure_rules.dart';
import 'exposure_visitors.dart';

/// Writes the Android API inventory: every class in scope, what Layer 1
/// exposes from it, and every member the rules leave out.
void writeAndroidInventory(
  File file, {
  required ast.Classes summary,
  required AndroidExposureRules rules,
  required List<CallbackClass> callbacks,
  required ExposureVisitors exposure,
  required String sdkPlatform,
}) {
  final decls =
      summary.decls.values.where((d) => rules.isInScope(d.binaryName)).toList()
        ..sort((a, b) => a.binaryName.compareTo(b.binaryName));
  final callbackNames = {for (final c in callbacks) c.binaryName: c};
  final omittedByClass = <String, List<OmittedMember>>{};
  for (final member in exposure.omitted) {
    omittedByClass.putIfAbsent(member.className, () => []).add(member);
  }

  final s = StringBuffer()
    ..writeln('# Android API inventory')
    ..writeln()
    ..writeln(
      'Generated by `tool/generate.dart` from `$sdkPlatform` '
      '(minimum API ${rules.minApi}). Do not edit.',
    )
    ..writeln()
    ..writeln(
      'Exposure: **full** = every public member after the omission '
      'rules; **type** = type only, so signatures that mention it stay '
      'typed.',
    )
    ..writeln();

  _summary(s, decls, rules, exposure);

  for (final package in {...decls.map((d) => d.packageName)}) {
    s
      ..writeln('## `$package`')
      ..writeln()
      ..writeln(
        '| Class | Kind | Since | Exposure | Methods | Fields | Notes |',
      )
      ..writeln('|---|---|---|---|---|---|---|');
    for (final decl in decls.where((d) => d.packageName == package)) {
      final name = decl.binaryName.substring(package.length + 1);
      final history = rules.levels.classHistory(decl.binaryName);
      final exposureLabel =
          rules.classExposure(decl.binaryName) == Exposure.full
          ? 'full'
          : 'type';
      final omitted = omittedByClass[decl.binaryName]?.length ?? 0;
      final methods = decl.methods.where((m) => m.isPublic).length - omitted;
      final notes = [
        if (callbackNames.containsKey(decl.binaryName))
          'implemented via `${decl.binaryName.split('.').last}.implement`',
        if (rules.isNonBluetooth(decl.binaryName)) 'non-Bluetooth technology',
        if (history?.deprecated case final deprecated?)
          'deprecated in $deprecated',
      ].join('; ');
      s.writeln(
        '| `$name` | ${decl.declKind.name.replaceAll('Kind', '')} '
        '| ${history?.since ?? '–'} | $exposureLabel '
        '| ${exposureLabel == 'full' ? methods : '–'} '
        '| ${exposureLabel == 'full' ? decl.fields.length : '–'} | $notes |',
      );
    }
    s.writeln();
  }

  s
    ..writeln('## Callback classes')
    ..writeln()
    ..writeln('| Class | Adapter | Callbacks | Lifetime |')
    ..writeln('|---|---|---|---|');
  for (final c in callbacks) {
    s.writeln(
      '| `${c.binaryName}` | `${c.adapterBinaryName}` | ${c.callbacks.length} '
      '| ${c.isService ? 'system-created service' : 'held by Java'} |',
    );
  }

  s
    ..writeln()
    ..writeln('## Omitted members')
    ..writeln()
    ..writeln('| Class | Member | Reason |')
    ..writeln('|---|---|---|');
  for (final member
      in exposure.omitted..sort(
        (a, b) =>
            '${a.className}${a.member}'.compareTo('${b.className}${b.member}'),
      )) {
    s.writeln(
      '| `${member.className}` | `${member.member}` '
      '| ${member.omission.reason} |',
    );
  }

  file
    ..createSync(recursive: true)
    ..writeAsStringSync(s.toString());
}

void _summary(
  StringBuffer s,
  List<ast.ClassDecl> decls,
  AndroidExposureRules rules,
  ExposureVisitors exposure,
) {
  final full = decls
      .where((d) => rules.classExposure(d.binaryName) == Exposure.full)
      .length;
  final counts = <Omission, int>{};
  for (final member in exposure.omitted) {
    counts[member.omission] = (counts[member.omission] ?? 0) + 1;
  }
  s
    ..writeln('| | Count |')
    ..writeln('|---|---|')
    ..writeln('| Classes in scope | ${decls.length} |')
    ..writeln('| Exposed in full | $full |')
    ..writeln('| Type only | ${decls.length - full} |');
  for (final omission in Omission.values) {
    s.writeln(
      '| Members omitted: ${omission.reason} | ${counts[omission] ?? 0} |',
    );
  }
  s.writeln();
}
