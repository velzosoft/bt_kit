/// Public top-level names declared by a generated bindings file.
Set<String> declaredNames(File bindings) {
  final unit = parseString(
    content: bindings.readAsStringSync(),
    throwIfDiagnostics: false,
  ).unit;
  return {
    for (final declaration in unit.declarations)
      if (_name(declaration) case final name? when !name.startsWith('_')) name,
  };
}

/// Generated names that would shadow `dart:core`, such as a `Duration` stub
/// for `java.time.Duration`, or clash with a runtime library exported next
/// to the bindings. Exporting them would silently change the meaning of
/// `Duration` in every file that imports Layer 1, or make the export
/// ambiguous.
Future<Set<String>> nameCollisions(
  File bindings,
  Set<String> names, {
  List<String> libraries = const ['dart:core'],
}) async {
  final path = bindings.absolute.path;
  final session = AnalysisContextCollection(includedPaths: [path])
      .contextFor(path)
      .currentSession;
  final taken = <String>{};
  for (final uri in libraries) {
    final library = await session.getLibraryByUri(uri);
    taken.addAll(
      (library as LibraryElementResult)
          .element
          .exportNamespace
          .definedNames2
          .keys,
    );
  }
  return names.intersection(taken);
}

/// Writes a library that re-exports [bindings] without [hidden], formatted
/// the way `dart format` leaves it.
Future<void> writeExports(
  File library, {
  required String header,
  required List<String> exports,
  required String bindings,
  required Iterable<String> hidden,
}) async {
  final names = hidden.toList()..sort();
  final hide = names.isEmpty
      ? ''
      : '\n    hide\n${names.map((n) => '        $n').join(',\n')}';
  final directives = [...exports, "export '$bindings'$hide;"];
  library.writeAsStringSync(
    '// Generated by tool/generate.dart. Do not edit.\n'
    '$header\n${directives.join('\n')}\n',
  );
  await Process.run('dart', ['format', library.path]);
}

String? _name(CompilationUnitMember declaration) => switch (declaration) {
  ClassDeclaration(:final namePart) => namePart.typeName.lexeme,
  MixinDeclaration(:final name) => name.lexeme,
  ExtensionTypeDeclaration(:final namePart) => namePart.typeName.lexeme,
  ExtensionDeclaration(:final name?) => name.lexeme,
  EnumDeclaration(:final namePart) => namePart.typeName.lexeme,
  FunctionDeclaration(:final name) => name.lexeme,
  TopLevelVariableDeclaration(:final variables) =>
    variables.variables.first.name.lexeme,
  _ => null,
};
