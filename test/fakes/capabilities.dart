import 'package:bt_kit/bt_kit.dart';

/// Every capability on, except those turned off.
BluetoothCapabilities capabilities({
  bool classic = true,
  bool extendedAdvertising = true,
  bool periodicAdvertising = true,
  bool channelSounding = true,
  bool bonding = true,
  bool removeBond = true,
  bool externalAccessory = true,
  bool companionDevices = true,
  bool backgroundEvents = true,
  bool stateRestoration = true,
  bool systemConnectionEvents = true,
  bool rssiRanging = true,
  bool audioProfiles = true,
  bool gattCacheRefresh = true,
  bool adapterName = true,
  bool serverConnectionPriority = true,
}) => BluetoothCapabilities(
  lowEnergy: true,
  classic: classic,
  le2MPhy: true,
  leCodedPhy: true,
  extendedAdvertising: extendedAdvertising,
  periodicAdvertising: periodicAdvertising,
  channelSounding: channelSounding,
  requestMtu: true,
  connectionPriority: true,
  phy: true,
  notifyMode: true,
  requestEnable: true,
  peripheralRole: true,
  advertiseLocalName: true,
  advertiseCustomData: true,
  l2cap: true,
  bonding: bonding,
  removeBond: removeBond,
  externalAccessory: externalAccessory,
  companionDevices: companionDevices,
  backgroundEvents: backgroundEvents,
  stateRestoration: stateRestoration,
  systemConnectionEvents: systemConnectionEvents,
  rssiRanging: rssiRanging,
  audioProfiles: audioProfiles,
  gattCacheRefresh: gattCacheRefresh,
  adapterName: adapterName,
  serverConnectionPriority: serverConnectionPriority,
);
